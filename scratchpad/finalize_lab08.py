from pathlib import Path

import nbformat
import pandas as pd

root = Path(__file__).resolve().parent.parent
path = root / 'lab_08.ipynb'
nb = nbformat.read(path, as_version=4)
nb.cells.append(nbformat.v4.new_markdown_cell('''## Выводы

Для распознавания кошек использованы 100 изображений кошек и 100 изображений собак. После изменения размера до 100 × 100 пикселей каждое изображение представлено вектором из 4356 HOG-признаков. Таблица `lab_08_hog.csv` содержит признаки, имя файла и метку класса. Для обучения выделено 160 изображений, для тестирования — 40, по 20 каждого класса.

На этом разбиении наибольшую accuracy показал SVM с RBF-ядром: 0,775, то есть 31 верное предсказание из 40. Random Forest получил 0,675, KNN — 0,575. F1 macro составляет примерно 0,775, 0,670 и 0,505 соответственно. При этих параметрах SVM лучше остальных различает два класса по HOG-признакам. У него 9 ошибок: 4 кошки определены как собаки, а 5 собак — как кошки.

На ошибочных изображениях встречаются перекрытия и необычные положения головы. В `cat.930.jpg` кошка опустила голову, часть тела закрыта рукой. На `cat.503.jpg` животное показано сверху на узорчатом фоне, а на `cat.427.jpg` рядом находятся две кошки. В `dog.216.jpg` собака вытянулась вверх к человеку, и привычный силуэт изменился. В этих случаях HOG описывает границы всего кадра, включая фон и соседние объекты. Предполагаю, что это мешает выделить признаки самого животного; визуальный просмотр не доказывает причину каждой ошибки.

Не все ошибки связаны со сложным фоном: на `dog.903.jpg` хорошо виден профиль собаки, но модель выбрала кошку. У этой собаки стоячие уши, поэтому отдельные контуры головы могут быть похожи на кошачьи. Это возможное объяснение, которое требует проверки на других изображениях.

Среди верных предсказаний есть фотографии, на которых различимы голова или силуэт одного животного: `cat.480.jpg`, `cat.128.jpg`, `dog.101.jpg`, `dog.300.jpg`. На `cat.929.jpg` чёрная кошка выделяется на светлом фоне, и модель распознаёт её верно. Однако встречаются удачные случаи и с помехами: `cat.635.jpg` распознана через решётку, а `dog.876.jpg` — в лежачем положении. Поэтому отдельный признак вроде наличия решётки или позы сам по себе не определяет успех классификации.

По просмотренным примерам модель справляется с частью кадров, где заметны характерные контуры головы и тела. Ошибки возникают при перекрытиях, нескольких животных в кадре и непривычных ракурсах, но эти наблюдения не являются строгой закономерностью. Для дальнейшего улучшения можно проверить выделение области животного перед HOG и расширить обучающую выборку похожими сложными примерами.

Результаты относятся к одному небольшому тесту. Модель для разбора выбрана после сравнения на этом же тесте, поэтому её результат не является независимой оценкой после выбора. Для более надёжного сравнения следует использовать кросс-валидацию на train и отдельный отложенный test. Отрицательный класс здесь состоит только из собак: работа не проверяет распознавание кошек среди любых возможных объектов.
'''))
nbformat.validate(nb)
assert all(o.output_type != 'error' for c in nb.cells if c.cell_type == 'code' for o in c.outputs)
assert all(c.execution_count is not None for c in nb.cells if c.cell_type == 'code')
assert all('???' not in c.source for c in nb.cells)
table = pd.read_csv(root / 'lab_08_hog.csv')
assert table.shape == (200, 4358)
assert table.filename.is_unique
assert table.label.value_counts().to_dict() == {1: 100, 0: 100}
assert all((row.filename.startswith('cats/') and row.label == 1)
           or (row.filename.startswith('dogs/') and row.label == 0)
           for row in table.itertuples())
assert table.drop(columns=['filename', 'label']).notna().all().all()
results = pd.read_csv(root / 'lab_08_model_comparison.csv')
assert len(results) == 3
nbformat.write(nb, path)
seminar = next(root.glob('*HOG*.ipynb'))
original = next(Path('E:/downloads').glob('*HOG*.ipynb'))
assert seminar.read_bytes() == original.read_bytes()
print('PASS: all code cells executed without errors; notebook format valid; HOG table 200 x 4358; labels and filenames match; three model results saved; source seminar unchanged.')
